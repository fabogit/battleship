// Room logic as a pure transition function (docs/server.md#room-state-machine, ADR-0037): no timers, sockets or I/O.

import {
  CLIENT_EVENTS,
  DEFAULT_RULES,
  ERROR_CODES,
  GAME_OVER_REASONS,
  otherSeat,
  PLACEMENT_TIME_LIMIT_MS,
  resolveTurn,
  ROOM_PHASES,
  SEATS,
  SERVER_EVENTS,
  shotsAllowed,
  TARGET_VIOLATIONS,
  validateDraft,
  validateFleet,
  validateRules,
  validateTargets,
  type Battle,
  type CommandPayload,
  type Coordinate,
  type ErrorCode,
  type GameRules,
  type JoinRoomPayload,
  type PlacedShip,
  type PlacementViolation,
  type RulesViolation,
  type Seat,
  type ShotResolvedPayload,
  type TargetViolation,
} from '@battleship/core';

/** A seated player as the server knows them; the secret never leaves the server except in the player's own ack. */
export interface RoomPlayer {
  /** Trimmed by the `CREATE_ROOM` / `JOIN_ROOM` guard. */
  readonly nickname: string;
  /** The seat's credential (docs/server.md#sessions--reconnection), generated by the caller, not by room logic. */
  readonly playerSecret: string;
}

/** One player's fleet during `PLACEMENT` (ADR-0005). */
export interface PlacementFleet {
  /** The latest draft that passed `validateDraft`, with derived coordinates; empty until the first update. */
  readonly ships: readonly PlacedShip[];
  /** Whether the player locked the fleet with `CONFIRM_PLACEMENT`; only a complete fleet can be locked. */
  readonly hasConfirmed: boolean;
}

/** What every phase of a room carries. */
interface RoomBase {
  /** `ROOM_ID_LENGTH` characters of `ROOM_ID_ALPHABET`, unique among the open rooms. */
  readonly roomId: string;
  /**
   * The rules the match is played with: `DEFAULT_RULES` in a new room, then the latest edit; kept when a player leaves
   * before the match (ADR-0083).
   */
  readonly rules: GameRules;
  /**
   * Bumped by every `UPDATE_RULES` that changes the rules, and never reset, so a stale `CONFIRM_RULES` can never match
   * a later version (ADR-0004); `0` in a new room.
   */
  readonly rulesVersion: number;
  /**
   * When each seat lost its last socket, in epoch ms; `null` while a socket is bound to it, and for an empty seat
   * (docs/server.md#seat-presence, ADR-0072). The forfeit clock counts `DISCONNECT_FORFEIT_MS` from it in every phase
   * but `GAME_OVER`. Room logic never sees sockets: the socket layer reports each change (`presence.ts`).
   */
  readonly disconnectedAt: Readonly<Record<Seat, number | null>>;
}

/**
 * A room with one seat taken: by its creator after `CREATE_ROOM`, or by the player left behind when the other freed
 * their seat before the match (ADR-0073), who keeps the seat they had.
 */
export interface WaitingRoom extends RoomBase {
  /** Discriminant: one seat taken. */
  readonly phase: typeof ROOM_PHASES.WAITING_FOR_OPPONENT;
  /** The seats, in the shape of the other phases' `players`: exactly one is empty, and `JOIN_ROOM` fills it. */
  readonly players:
    | {
        /** The creator, or a joiner whose opponent left. */
        readonly P1: RoomPlayer;
        /** Empty until `JOIN_ROOM`. */
        readonly P2: null;
      }
    | {
        /** Freed by a creator who left or forfeited; the next `JOIN_ROOM` takes it. */
        readonly P1: null;
        /** A joiner whose opponent left before the match. */
        readonly P2: RoomPlayer;
      };
}

/** A room where both players agree on the rules (ADR-0003): either may edit them, and both confirm one version. */
export interface NegotiationRoom extends RoomBase {
  /** Discriminant: the rules are being agreed on. */
  readonly phase: typeof ROOM_PHASES.RULES_NEGOTIATION;
  /** Both seats are taken from here on. */
  readonly players: Readonly<Record<Seat, RoomPlayer>>;
  /** Whether each seat confirmed the current `rulesVersion`; an edit clears both. */
  readonly hasConfirmedRules: Readonly<Record<Seat, boolean>>;
}

/** A room where both players place their fleets. */
export interface PlacementRoom extends RoomBase {
  /** Discriminant: fleets are being placed. */
  readonly phase: typeof ROOM_PHASES.PLACEMENT;
  /** Both seats are taken from here on. */
  readonly players: Readonly<Record<Seat, RoomPlayer>>;
  /** Each seat's draft or locked fleet. */
  readonly fleets: Readonly<Record<Seat, PlacementFleet>>;
  /**
   * When unconfirmed fleets will be completed and locked, in epoch ms: `PLACEMENT_TIME_LIMIT_MS` after phase entry.
   * Only projected as `remainingMs` until the placement timer enforces it (#28).
   */
  readonly deadline: number;
}

/** A room whose match is being played. */
export interface BattleRoom extends RoomBase {
  /** Discriminant: the match is on. */
  readonly phase: typeof ROOM_PHASES.IN_PROGRESS;
  /** Both seats are taken. */
  readonly players: Readonly<Record<Seat, RoomPlayer>>;
  /** Boards and turn, as `resolveTurn` returns them (ADR-0033). */
  readonly battle: Battle;
  /** The current turn's draft from `UPDATE_TARGETS`; cleared whenever the turn is fired. */
  readonly draftTargets: readonly Coordinate[];
  /**
   * Whether the turn timer is frozen (ADR-0008, ADR-0074): set when a seat loses its last socket, cleared when both
   * are connected again, and switched by `SET_PAUSED` from the connected player while the opponent is away. Nothing
   * else stops while paused: the forfeit clock runs and the active player may still fire.
   */
  readonly isPaused: boolean;
}

/** A room whose match has ended. */
export interface GameOverRoom extends RoomBase {
  /** Discriminant: the match has ended. */
  readonly phase: typeof ROOM_PHASES.GAME_OVER;
  /** Both seats are taken. */
  readonly players: Readonly<Record<Seat, RoomPlayer>>;
  /** The final boards; both fleets are revealed from here on. */
  readonly battle: Battle;
  /** The seat that sank the opponent's last ship. */
  readonly winner: Seat;
  /** How the match ended; surrender (#35) and AFK (#30) add their reasons when they land. */
  readonly reason: GameOverRoomReason;
}

/** The ways a match can end so far: the last ship sunk, or a seat away for `DISCONNECT_FORFEIT_MS` (ADR-0072). */
export type GameOverRoomReason = typeof GAME_OVER_REASONS.FLEET_DESTROYED | typeof GAME_OVER_REASONS.DISCONNECT_FORFEIT;

/** Everything the server keeps about one room, one variant per phase it can be in (ADR-0037). */
export type RoomState = WaitingRoom | NegotiationRoom | PlacementRoom | BattleRoom | GameOverRoom;

/** Commands a seated player sends, handled by `applyCommand`; `RoomManager.dispatch` runs them for the socket handlers. */
export type SeatCommandEvent =
  | typeof CLIENT_EVENTS.UPDATE_RULES
  | typeof CLIENT_EVENTS.CONFIRM_RULES
  | typeof CLIENT_EVENTS.UPDATE_PLACEMENT
  | typeof CLIENT_EVENTS.CONFIRM_PLACEMENT
  | typeof CLIENT_EVENTS.UNLOCK_PLACEMENT
  | typeof CLIENT_EVENTS.UPDATE_TARGETS
  | typeof CLIENT_EVENTS.FIRE
  | typeof CLIENT_EVENTS.SET_PAUSED;

/** The rules commands, handled by `applyRulesCommand`. */
type RulesCommandEvent = typeof CLIENT_EVENTS.UPDATE_RULES | typeof CLIENT_EVENTS.CONFIRM_RULES;

/** The placement commands, handled by `applyPlacementCommand`. */
type PlacementCommandEvent =
  | typeof CLIENT_EVENTS.UPDATE_PLACEMENT
  | typeof CLIENT_EVENTS.CONFIRM_PLACEMENT
  | typeof CLIENT_EVENTS.UNLOCK_PLACEMENT;

/** The turn commands, handled by `applyBattleCommand`. */
type BattleCommandEvent = typeof CLIENT_EVENTS.UPDATE_TARGETS | typeof CLIENT_EVENTS.FIRE;

/**
 * A command from a seated player: the event, the sender's seat (the caller maps the socket to it) and the payload
 * as its core guard returned it (ADR-0031).
 */
export type SeatCommand = {
  [E in SeatCommandEvent]: {
    /** The protocol event. */
    readonly type: E;
    /** The sender. */
    readonly seat: Seat;
    /** The guard's normalized copy of the payload. */
    readonly payload: CommandPayload<E>;
  };
}[SeatCommandEvent];

/** `JOIN_ROOM`, which comes from a player without a seat yet. */
export interface JoinRoomCommand {
  /** The protocol event. */
  readonly type: typeof CLIENT_EVENTS.JOIN_ROOM;
  /** The guard's normalized copy of the payload; the caller already used `roomId` to find the room. */
  readonly payload: JoinRoomPayload;
  /** The joiner's new secret, generated by the caller, which also returns it in the ack. */
  readonly playerSecret: string;
}

/** Every command `applyCommand` handles; `CREATE_ROOM` builds a room with `createRoom` instead. */
export type RoomCommand = JoinRoomCommand | SeatCommand;

/**
 * Something the caller must do besides sending `STATE`, which it sends to every seated player after any accepted
 * command (ADR-0037). Timer scheduling (#28, #30) and `DICE_ROLLED` (#29) will join this union.
 */
export interface ShotResolvedEffect {
  /** Discriminant, named after the event to emit to both players. */
  readonly type: typeof SERVER_EVENTS.SHOT_RESOLVED;
  /** The event payload, for animation and sound. */
  readonly payload: ShotResolvedPayload;
}

/** What the caller must do after an accepted command, besides sending `STATE`. */
export type RoomEffect = ShotResolvedEffect;

/** An accepted command: the room after it, and what the caller does next. */
export interface AcceptedTransition {
  /** Discriminant: the ack reports success. */
  readonly ok: true;
  /** The room after the command; the same object when the command changed nothing (a repeated confirm or unlock). */
  readonly state: RoomState;
  /** In the order the caller must perform them. */
  readonly effects: readonly RoomEffect[];
}

/** A refused command: the room is left as it was, and `error` goes back in the ack. */
export interface RejectedTransition {
  /** Discriminant: the ack reports `error`. */
  readonly ok: false;
  /** What the ack reports (docs/protocol.md#error-codes). */
  readonly error: ErrorCode;
  /**
   * For `INVALID_RULES`, `INVALID_PLACEMENT` and `INVALID_TARGETS`, the rule broken; for the server log only, never sent
   * (ADR-0032).
   */
  readonly violation?: Violation;
}

/** Outcome of `applyCommand`. */
export type TransitionResult = AcceptedTransition | RejectedTransition;

/** The core violations a refused command can carry. */
export type Violation = RulesViolation | PlacementViolation | TargetViolation;

/** Neither seat has confirmed the current rules. */
const NO_CONFIRMATIONS: Readonly<Record<Seat, boolean>> = { P1: false, P2: false };

/** A placement fleet before the player's first update. */
const EMPTY_FLEET: PlacementFleet = { ships: [], hasConfirmed: false };

/** The seat that starts every match until the dice roll lands (#29). */
const FIRST_SEAT: Seat = SEATS.P1;

/** Both seats connected, or empty: no forfeit clock running. */
const ALL_CONNECTED: Readonly<Record<Seat, number | null>> = { P1: null, P2: null };

/**
 * Opens a room in `WAITING_FOR_OPPONENT` with `DEFAULT_RULES` and seats the creator as `P1` (`CREATE_ROOM`).
 * @param roomId A fresh id, unique among the open rooms; the caller generates it.
 * @param creator The creator's nickname, as the guard returned it, and their new secret.
 * @returns The new room.
 */
export function createRoom(roomId: string, creator: RoomPlayer): WaitingRoom {
  return {
    phase: ROOM_PHASES.WAITING_FOR_OPPONENT,
    roomId,
    rules: DEFAULT_RULES,
    rulesVersion: 0,
    players: { P1: creator, P2: null },
    disconnectedAt: ALL_CONNECTED,
  };
}

/**
 * Applies one command to a room (docs/server.md#transition-rules). Pure: the input is never mutated, and a refused
 * command returns no state, so the caller keeps the room it had.
 * @param state The room before the command.
 * @param command The command, with a payload that already passed its guard.
 * @param now Current time in epoch ms; deadlines are stored as timestamps and projected as remaining time.
 * @returns The new room and the effects to perform, or the error for the ack.
 */
export function applyCommand(state: RoomState, command: RoomCommand, now: number): TransitionResult {
  switch (command.type) {
    case CLIENT_EVENTS.JOIN_ROOM:
      return joinRoom(state, command);
    case CLIENT_EVENTS.UPDATE_RULES:
    case CLIENT_EVENTS.CONFIRM_RULES:
      return state.phase === ROOM_PHASES.RULES_NEGOTIATION
        ? applyRulesCommand(state, command, now)
        : reject(ERROR_CODES.WRONG_PHASE);
    case CLIENT_EVENTS.UPDATE_PLACEMENT:
    case CLIENT_EVENTS.CONFIRM_PLACEMENT:
    case CLIENT_EVENTS.UNLOCK_PLACEMENT:
      return state.phase === ROOM_PHASES.PLACEMENT
        ? applyPlacementCommand(state, command)
        : reject(ERROR_CODES.WRONG_PHASE);
    case CLIENT_EVENTS.UPDATE_TARGETS:
    case CLIENT_EVENTS.FIRE:
      return state.phase === ROOM_PHASES.IN_PROGRESS
        ? applyBattleCommand(state, command)
        : reject(ERROR_CODES.WRONG_PHASE);
    case CLIENT_EVENTS.SET_PAUSED:
      return state.phase === ROOM_PHASES.IN_PROGRESS ? setPaused(state, command) : reject(ERROR_CODES.WRONG_PHASE);
  }
}

/**
 * Builds the room at the end of a match: both fleets are revealed from here on (docs/server.md#game-over--rematch).
 * @param state The room in `IN_PROGRESS`.
 * @param battle The final boards.
 * @param winner The seat that won.
 * @param reason How the match ended.
 * @returns The room in `GAME_OVER`; seat presence carries over, but no forfeit clock runs in it.
 */
export function endMatch(state: BattleRoom, battle: Battle, winner: Seat, reason: GameOverRoomReason): GameOverRoom {
  return {
    phase: ROOM_PHASES.GAME_OVER,
    roomId: state.roomId,
    rules: state.rules,
    rulesVersion: state.rulesVersion,
    players: state.players,
    disconnectedAt: state.disconnectedAt,
    battle,
    winner,
    reason,
  };
}

/**
 * Seats the joiner in the free seat, `P2` unless the creator has left (ADR-0073), and starts rules negotiation. A room
 * with both seats taken is `ROOM_FULL` in every phase, so `JOIN_ROOM` never answers `WRONG_PHASE`.
 * @param state The room the payload's `roomId` named, in any phase.
 * @param command The join, with the joiner's nickname and secret.
 * @returns The room in `RULES_NEGOTIATION` with the room's rules and version and no confirmation, or `ROOM_FULL`. A
 * seated player who is away stays away, with their forfeit clock.
 */
function joinRoom(state: RoomState, command: JoinRoomCommand): TransitionResult {
  if (state.phase !== ROOM_PHASES.WAITING_FOR_OPPONENT) {
    return reject(ERROR_CODES.ROOM_FULL);
  }
  const joiner: RoomPlayer = { nickname: command.payload.nickname, playerSecret: command.playerSecret };
  const seated = state.players;
  return accept({
    phase: ROOM_PHASES.RULES_NEGOTIATION,
    roomId: state.roomId,
    rules: state.rules,
    rulesVersion: state.rulesVersion,
    players: seated.P1 === null ? { P1: joiner, P2: seated.P2 } : { P1: seated.P1, P2: joiner },
    disconnectedAt: state.disconnectedAt,
    hasConfirmedRules: NO_CONFIRMATIONS,
  });
}

/**
 * Handles the rules commands (docs/server.md#rules-negotiation, ADR-0003, ADR-0004, ADR-0082). Either player may
 * edit: an edit that changes the rules bumps `rulesVersion` and clears both confirmations, an edit to the rules already
 * in place changes nothing. A confirmation names the version it accepts; when both seats have confirmed the current
 * one, placement starts with those rules.
 * @param state The room in `RULES_NEGOTIATION`.
 * @param command `UPDATE_RULES` or `CONFIRM_RULES`.
 * @param now Current time in epoch ms; the placement deadline counts from it.
 * @returns The updated room (the same object when nothing changed), or `INVALID_RULES` with the violation, or
 * `STALE_RULES` for a confirmation of any other version.
 */
function applyRulesCommand(
  state: NegotiationRoom,
  command: Extract<SeatCommand, { type: RulesCommandEvent }>,
  now: number,
): TransitionResult {
  if (command.type === CLIENT_EVENTS.UPDATE_RULES) {
    const { rules } = command.payload;
    const validation = validateRules(rules);
    if (!validation.ok) {
      return reject(ERROR_CODES.INVALID_RULES, validation.reason);
    }
    if (areSameRules(rules, state.rules)) {
      return accept(state);
    }
    return accept({ ...state, rules, rulesVersion: state.rulesVersion + 1, hasConfirmedRules: NO_CONFIRMATIONS });
  }

  if (command.payload.rulesVersion !== state.rulesVersion) {
    return reject(ERROR_CODES.STALE_RULES);
  }
  if (state.hasConfirmedRules[command.seat]) {
    return accept(state);
  }
  const hasConfirmedRules = { ...state.hasConfirmedRules, [command.seat]: true };
  return accept(
    hasConfirmedRules.P1 && hasConfirmedRules.P2 ? startPlacement(state, now) : { ...state, hasConfirmedRules },
  );
}

/**
 * Whether two rules objects hold the same values, field by field.
 * @param left Well-formed rules.
 * @param right Well-formed rules.
 * @returns `true` when every field matches.
 */
function areSameRules(left: GameRules, right: GameRules): boolean {
  return (Object.keys(left) as (keyof GameRules)[]).every((field) => left[field] === right[field]);
}

/**
 * Moves a room whose rules both players confirmed into placement, with empty fleets and the deadline counting from now.
 * @param state The room in `RULES_NEGOTIATION`.
 * @param now Current time in epoch ms.
 * @returns The room in `PLACEMENT`, with the agreed rules and their version.
 */
function startPlacement(state: NegotiationRoom, now: number): PlacementRoom {
  return {
    phase: ROOM_PHASES.PLACEMENT,
    roomId: state.roomId,
    rules: state.rules,
    rulesVersion: state.rulesVersion,
    players: state.players,
    disconnectedAt: state.disconnectedAt,
    fleets: { P1: EMPTY_FLEET, P2: EMPTY_FLEET },
    deadline: now + PLACEMENT_TIME_LIMIT_MS,
  };
}

/**
 * Handles the placement commands (docs/server.md#placement): draft updates, confirmation and unlock. The second
 * confirmation starts the match at once, `P1` first; the start countdown (#28) and the dice roll (#29) come later.
 * @param state The room in `PLACEMENT`.
 * @param command A placement command.
 * @returns The updated room, or the error for the ack.
 */
function applyPlacementCommand(
  state: PlacementRoom,
  command: Extract<SeatCommand, { type: PlacementCommandEvent }>,
): TransitionResult {
  const fleet = state.fleets[command.seat];
  switch (command.type) {
    case CLIENT_EVENTS.UPDATE_PLACEMENT: {
      if (fleet.hasConfirmed) {
        return reject(ERROR_CODES.PLACEMENT_LOCKED);
      }
      const validation = validateDraft(command.payload.ships, state.rules);
      if (!validation.ok) {
        return reject(ERROR_CODES.INVALID_PLACEMENT, validation.reason);
      }
      return accept(withFleet(state, command.seat, { ships: validation.ships, hasConfirmed: false }));
    }
    case CLIENT_EVENTS.CONFIRM_PLACEMENT: {
      if (fleet.hasConfirmed) {
        return accept(state);
      }
      const validation = validateFleet(fleet.ships, state.rules);
      if (!validation.ok) {
        return reject(ERROR_CODES.INVALID_PLACEMENT, validation.reason);
      }
      const next = withFleet(state, command.seat, { ships: fleet.ships, hasConfirmed: true });
      return accept(next.fleets.P1.hasConfirmed && next.fleets.P2.hasConfirmed ? startBattle(next) : next);
    }
    case CLIENT_EVENTS.UNLOCK_PLACEMENT:
      return accept(
        fleet.hasConfirmed ? withFleet(state, command.seat, { ships: fleet.ships, hasConfirmed: false }) : state,
      );
  }
}

/**
 * Handles the turn commands (docs/server.md#turns): the active player's draft and the shot itself.
 * @param state The room in `IN_PROGRESS`.
 * @param command `UPDATE_TARGETS` or `FIRE`.
 * @returns The updated room with `SHOT_RESOLVED` after a fired turn, or the error for the ack.
 */
function applyBattleCommand(
  state: BattleRoom,
  command: Extract<SeatCommand, { type: BattleCommandEvent }>,
): TransitionResult {
  const { battle } = state;
  if (command.seat !== battle.currentTurn) {
    return reject(ERROR_CODES.NOT_YOUR_TURN);
  }
  const { targets } = command.payload;
  if (command.type === CLIENT_EVENTS.UPDATE_TARGETS) {
    // A draft may hold any count up to the allowance; every other target rule applies as to a shot.
    if (targets.length > shotsAllowed(battle, state.rules)) {
      return reject(ERROR_CODES.INVALID_TARGETS, TARGET_VIOLATIONS.WRONG_TARGET_COUNT);
    }
    const shots = battle.boards[otherSeat(battle.currentTurn)].shots;
    const validation = validateTargets(targets, shots, targets.length);
    if (!validation.ok) {
      return reject(ERROR_CODES.INVALID_TARGETS, validation.reason);
    }
    return accept({ ...state, draftTargets: targets });
  }

  const resolution = resolveTurn(battle, targets, state.rules);
  if (!resolution.ok) {
    return reject(ERROR_CODES.INVALID_TARGETS, resolution.reason);
  }
  const effects: RoomEffect[] = [
    { type: SERVER_EVENTS.SHOT_RESOLVED, payload: { shooter: command.seat, results: resolution.results } },
  ];
  if (resolution.winner !== null) {
    return accept(endMatch(state, resolution.battle, resolution.winner, GAME_OVER_REASONS.FLEET_DESTROYED), effects);
  }
  return accept({ ...state, battle: resolution.battle, draftTargets: [] }, effects);
}

/**
 * Pauses or resumes the match (`SET_PAUSED`, docs/server.md#disconnection--pause-in_progress): only while the sender's
 * opponent is away, and the sender is connected since it sends. Asking for the state the match is already in is
 * accepted and changes nothing, like a repeated confirm.
 * @param state The room in `IN_PROGRESS`.
 * @param command `SET_PAUSED`, with the wanted state.
 * @returns The room with the new pause state, or `NOT_ALLOWED` while the opponent is connected.
 */
function setPaused(
  state: BattleRoom,
  command: Extract<SeatCommand, { type: typeof CLIENT_EVENTS.SET_PAUSED }>,
): TransitionResult {
  if (state.disconnectedAt[otherSeat(command.seat)] === null) {
    return reject(ERROR_CODES.NOT_ALLOWED);
  }
  const { isPaused } = command.payload;
  return accept(state.isPaused === isPaused ? state : { ...state, isPaused });
}

/**
 * Moves a room whose fleets are both confirmed into battle, with empty shot lists and `FIRST_SEAT` to fire. A player
 * who is away at that moment finds the match paused (docs/server.md#placement).
 * @param state The room in `PLACEMENT`, both fleets confirmed.
 * @returns The room in `IN_PROGRESS`.
 */
function startBattle(state: PlacementRoom): BattleRoom {
  return {
    phase: ROOM_PHASES.IN_PROGRESS,
    roomId: state.roomId,
    rules: state.rules,
    rulesVersion: state.rulesVersion,
    players: state.players,
    disconnectedAt: state.disconnectedAt,
    battle: {
      boards: {
        P1: { ships: state.fleets.P1.ships, shots: [] },
        P2: { ships: state.fleets.P2.ships, shots: [] },
      },
      currentTurn: FIRST_SEAT,
    },
    draftTargets: [],
    isPaused: state.disconnectedAt.P1 !== null || state.disconnectedAt.P2 !== null,
  };
}

/**
 * Replaces one seat's placement fleet.
 * @param state The room in `PLACEMENT`.
 * @param seat The seat whose fleet changes.
 * @param fleet The new fleet.
 * @returns A new room; the other seat's fleet is shared, not copied.
 */
function withFleet(state: PlacementRoom, seat: Seat, fleet: PlacementFleet): PlacementRoom {
  return { ...state, fleets: { ...state.fleets, [seat]: fleet } };
}

/**
 * Builds an accepted result, so each transition ends in one readable `return`.
 * @param state The room after the command.
 * @param effects What the caller must do besides sending `STATE`; none by default.
 * @returns `{ ok: true, state, effects }`.
 */
function accept(state: RoomState, effects: readonly RoomEffect[] = []): AcceptedTransition {
  return { ok: true, state, effects };
}

/**
 * Builds a refused result, so each transition ends in one readable `return`.
 * @param error The code for the ack.
 * @param violation The rule broken, for `INVALID_RULES`, `INVALID_PLACEMENT` and `INVALID_TARGETS`.
 * @returns `{ ok: false, error }`, plus `violation` only when one is given: the key is left out rather than set to
 * `undefined`.
 */
function reject(error: ErrorCode, violation?: Violation): RejectedTransition {
  return violation === undefined ? { ok: false, error } : { ok: false, error, violation };
}
